  `Fconv_id` CHAR(12) NOT NULL,
  `Fseq` BIGINT NOT NULL,
  `Frun_id` CHAR(26) NOT NULL DEFAULT '',
  `Fsource` TINYINT NOT NULL,
  `Ftype` VARCHAR(32) NOT NULL,
  `Fruntime_epoch` VARCHAR(64) NULL,
  `Fagent_session_id` VARCHAR(40) NULL,
